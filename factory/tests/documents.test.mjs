test('Word evidence requires docx and file-bound completed page review', () => {
  const bytes = wordFixture(), commit = 'a'.repeat(40);
  const guide = { kind: 'developer', status: 'complete', commit, format: 'docx', entry: 'docs/developer.docx', verification: reviewFixture(bytes) };
  assert.equal(wordEvidence(guide, commit), true);
  for (const bad of [{ ...guide, format: 'markdown' }, { ...guide, entry: 'docs/developer.md' }, { ...guide, verification: undefined }, { ...guide, verification: { ...guide.verification, status: 'not-checked' } }, { ...guide, verification: { ...guide.verification, sha256: 'not-a-hash' } }, { ...guide, verification: { ...guide.verification, pages: 0 } }]) assert.equal(wordEvidence(bad, commit), false);
});
test('bounded package checks accept stored/deflated Word and reject renamed text, unrelated ZIPs and corrupt content', () => {
  for (const compressed of [true, false]) assert.equal(inspectWord(wordFixture('developer', compressed)).sha256, reviewFixture(wordFixture('developer', compressed)).sha256);
  assert.throws(() => inspectWord(Buffer.from('# Markdown renamed to .docx')), /Word/);
  assert.throws(() => inspectWord(zipFixture({ 'unrelated.txt': 'Not a Word document' })), /Word/);
  const corrupt = wordFixture(); corrupt[40] ^= 1; assert.throws(() => inspectWord(corrupt));
  const parts = wordParts(); delete parts['_rels/.rels']; assert.throws(() => inspectWord(zipFixture(parts)), /Word/);
  assert.throws(() => inspectWord(zipFixture({ ...wordParts(), '../escape': 'Unsafe package name' })), /Word/);
  assert.throws(() => inspectWord(zipFixture({ ...wordParts(), 'word/vbaProject.bin': 'Not a .docx guide' })), /Word/);
  const macro = wordParts(); macro['[Content_Types].xml'] = macro['[Content_Types].xml'].replace('wordprocessingml.document.main+xml', 'wordprocessingml.template.main+xml');
  assert.throws(() => inspectWord(zipFixture(macro)), /Word/);
});
test('authenticated Word downloads use only registered committed guides and preserve exact reviewed bytes', async t => {
  const root = await mkdtemp(path.join(tmpdir(), 'factory-word-')); let server;
  t.after(async () => { if (server) await server.close(); assert.equal(path.dirname(root), path.resolve(tmpdir())); assert.ok(path.basename(root).startsWith('factory-word-')); await rm(root, { recursive: true, force: true }); });
  await git(root, ['init', '-b', 'main']); await mkdir(path.join(root, 'docs'));
  const bytes = wordFixture(); await writeFile(path.join(root, 'docs/developer.docx'), bytes);
  await git(root, ['add', 'docs/developer.docx']); await git(root, ['-c', 'user.name=Word Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '-m', 'Synthetic Word fixture']);
  const commit = await git(root, ['rev-parse', 'HEAD']);
  await install(await planInstall(root, 'claude-only')); server = await serve(root);
  const connection = await json(path.join(root, 'factory/.local/connection.json'));
  const state = await readState(root), job = newLifecycle({ input: { title: 'Word download fixture', mode: 'feature', requirements: 'Synthetic download test' } });
  job.status = 'merged'; job.commit = commit;
  const guide = { kind: 'developer', format: 'docx', status: 'complete', entry: 'docs/developer.docx', commit, verification: reviewFixture(bytes) };
  job.documentation = [guide]; state.jobs.push(job); await atomic(path.join(root, 'factory/.local/state.json'), state);
  const url = server.origin + '/api/documents?job=' + job.id + '&kind=developer';
  assert.equal((await fetch(url)).status, 401);
  const headers = { Authorization: 'Bearer ' + connection.browser_key };
  const response = await fetch(url, { headers }); assert.equal(response.status, 200);
  assert.equal(response.headers.get('content-type'), WORD_MIME); assert.match(response.headers.get('content-disposition'), /attachment; filename="developer-guide.docx"/);
  assert.deepEqual(Buffer.from(await response.arrayBuffer()), bytes);
  await writeFile(path.join(root, 'docs/developer.docx'), 'Uncommitted changes must not replace reviewed downloads');
  assert.deepEqual(Buffer.from(await (await fetch(url, { headers })).arrayBuffer()), bytes);
  assert.equal((await fetch(url + '&feature=unknown', { headers })).status, 400);
  assert.equal((await fetch(server.origin + '/api/documents?job=' + job.id + '&kind=secrets', { headers })).status, 400);
  assert.deepEqual(await committedWord(root, guide, commit), bytes);
  const legacy = newLifecycle({ input: { title: 'Old staged work', mode: 'feature', requirements: 'Keep previous source' } });
  delete legacy.documentation_format; legacy.cursor = 4; legacy.status = 'awaiting-stage'; legacy.plan = { summary: 'Previous scope' }; legacy.approved_plan_hash = 'old-consent';
  legacy.stages = [{ stage: 'specification', approved: true, content: 'Preserve this history' }];
  state.jobs.push(legacy); await atomic(path.join(root, 'factory/.local/state.json'), state);
  await server.close(); server = await serve(root);
  const migrated = (await readState(root)).jobs.find(j => j.id === legacy.id);
  assert.equal(migrated.status, 'blocked'); assert.equal(migrated.documentation_format, 'docx'); assert.equal(migrated.approved_plan_hash, null);
  assert.equal(migrated.stages[0].content, 'Preserve this history');
  assert.throws(() => validateLifecycleCommand({ commands: [] }, { action: 'revise', input: { note: 'Try to skip the format revision', stage: 'implementation' } }, migrated), /Revise specification/);
  await assert.rejects(committedWord(root, { ...guide, verification: { ...guide.verification, sha256: '0'.repeat(64) } }, commit), /changed since/);
  await assert.rejects(committedWord(root, { ...guide, entry: '../outside.docx' }, commit), /Unsafe/);
  await assert.rejects(committedWord(root, { ...guide, entry: 'factory/.local/private.docx' }, commit), /committed application/);
});
